namespace RecursiveAI.OneLite.Tests.Engine;

/// <summary>
/// Aggregates written in a subquery but owned by an enclosing query (lang_aggfunc), HAVING on a query with no aggregate of its own, and the
/// affinity of the values an IN (SELECT ...) set holds. Expected texts were recorded from the pinned sqlite3 3.53.4.
