        => Assert.Equal(expected, ColumnDefaultTests.Run(Setup + sql));

    // A REAL left side keeps REAL for the set (an integer becomes floating point); '=' and NUMERIC columns do not do that.
    [Theory]
    [InlineData("select count(*) from r where c in (select 9007199254740993)", "1")]
    [InlineData("select count(*) from r where c in (select 9007199254740993 union all select 1)", "1")]
    [InlineData("select count(*) from r where c = (select 9007199254740993)", "0")]
    [InlineData("select count(*) from r where c in (9007199254740993)", "0")]
    [InlineData("select count(*) from r where n in (select 9007199254740993)", "0")]
    [InlineData("select count(*) from r where i in (select '5' union all select 1)", "1")]
    [InlineData("select count(*) from r where tx in (select 5 union all select 1)", "1")]
    public void ARealLeftSideAppliesRealToTheSet(string sql, string expected)
        => Assert.Equal(expected, ColumnDefaultTests.Run("create table r(c real, n numeric, i integer, x, tx text); insert into r values(9007199254740992.0, 9007199254740992.0, 5, 9007199254740992.0, '5'); " + sql));
