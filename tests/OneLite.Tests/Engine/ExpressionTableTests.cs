    [Fact]
    public void ExpressionsMatchRecordedShellOutput()
    {
        Assert.SkipUnless(File.Exists(OraclePaths.Cli), "the pinned sqlite3 shell is not installed");
        string path = Path.Combine(_dir, "x.db");
        SqliteCli.ApplyScript(path, "CREATE TABLE t(x);");
        using var db = Database.OpenReadOnly(path);
        using Connection conn = db.Connect();
        var failures = new StringBuilder();
        foreach (var (expr, expected) in s_cases)
        {
            string got;
            try
            {
                using Statement st = conn.Prepare("SELECT quote(" + expr + ");");
                got = st.Step() ? Encoding.UTF8.GetString(st.GetTextUtf8(0)) : "<no row>";
            }
            catch (Exception ex)
            {
                got = "<" + ex.GetType().Name + ": " + ex.Message + ">";
            }
            if (got != expected) failures.Append(expr).Append(" => ").Append(got).Append(" (expected ").Append(expected).Append(")\n");
        }
        Assert.True(failures.Length == 0, failures.ToString());
    }
