#!/usr/bin/env python3
"""Generates src/OneLite/Internal/Text/UnicodeTables.g.cs from the Unicode Character Database.

The FTS unicode61 tokenizer is documented to follow Unicode 6.1 (sqlite.org/fts5.html, "tokenchars"), and observed behaviour of the
reference shell agrees with that version, so the tables are built from the 6.1.0 files:
  UnicodeData.txt  -> general category runs; canonical decompositions (for diacritic removal)
  CaseFolding.txt  -> simple case folding (status C and S)

Usage: gen_unicode_tables.py [ucd-dir]   (default ~/onelite/cache/ucd; missing files are downloaded)
"""
import os, sys, urllib.request

ucd = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/onelite/cache/ucd')
os.makedirs(ucd, exist_ok=True)
BASE = 'https://www.unicode.org/Public/6.1.0/ucd/'

def get(name):
    p = os.path.join(ucd, name.replace('.txt', '-6.1.0.txt'))
    if not os.path.exists(p):
        urllib.request.urlretrieve(BASE + name, p)
    return p

CATS = ['Cn', 'Lu', 'Ll', 'Lt', 'Lm', 'Lo', 'Mn', 'Mc', 'Me', 'Nd', 'Nl', 'No', 'Pc', 'Pd', 'Ps', 'Pe', 'Pi', 'Pf', 'Po',
        'Sm', 'Sc', 'Sk', 'So', 'Zs', 'Zl', 'Zp', 'Cc', 'Cf', 'Cs', 'Co']
cat = {}
dec = {}
rng = None
for line in open(get('UnicodeData.txt'), encoding='utf8'):
    f = line.split(';')
    cp = int(f[0], 16)
    if f[1].endswith(', First>'):
        rng = cp
        continue
    if f[1].endswith(', Last>'):
        for c in range(rng, cp + 1):
            cat[c] = f[2]
        continue
    cat[cp] = f[2]
    if f[5] and not f[5].startswith('<'):
        dec[cp] = [int(x, 16) for x in f[5].split()]

fold = {}
for line in open(get('CaseFolding.txt')):
    if line.startswith('#') or not line.strip():
        continue
    a, s, m, _ = [x.strip() for x in line.split(';')[:4]]
    if s in ('C', 'S'):
        fold[int(a, 16)] = int(m, 16)

# Combining marks the tokenizer treats as removable diacritics: observed behaviour of the reference shell (all of U+0300..U+036F
# that occur in Latin decompositions of Unicode 6.1).
MARKS = []
for r in '300-304 306-30c 30f 311 31b 323-328 32d-32e 330-331'.split():
    a, _, b = r.partition('-')
    a = int(a, 16)
    b = int(b, 16) if b else a
    MARKS += range(a, b + 1)
MARKS = set(MARKS)

def nfd(c):
    if c in dec:
        o = []
        for x in dec[c]:
            o += nfd(x)
        return o
    return [c]

# (cp, base, number of marks) for letters whose full decomposition is a Latin base plus only removable marks.
dia = []
for c in sorted(dec):
    n = nfd(c)
    if len(n) > 1 and all(m in MARKS for m in n[1:]) and (n[0] < 128 or n[0] == 0x17f):
        # Observed exception: U+01E0 and U+01E1 keep their marks even at remove_diacritics=2.
        if c in (0x1e0, 0x1e1):
            continue
        dia.append((c, n[0], len(n) - 1))

runs = []
prev = None
for c in range(0x110000):
    k = CATS.index(cat.get(c, 'Cn'))
    if k != prev:
        runs.append((c, k))
        prev = k

def arr(name, typ, vals, per=12):
    out = ['    internal static readonly %s[] %s =\n    [' % (typ, name)]
    for i in range(0, len(vals), per):
        out.append('        ' + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    out.append('    ];')
    return '\n'.join(out)

fk = sorted(fold)
src = ['// <auto-generated> by tools/fts/gen_unicode_tables.py from the Unicode 6.1.0 Character Database. Do not edit. </auto-generated>',
       'namespace RecursiveAI.OneLite.Internal.Text;', '',
       'internal static class UnicodeTables', '{',
       '    /// <summary>General category names; the index is the category code used by <see cref="CatCode"/>.</summary>',
       '    internal static readonly string[] CategoryNames = [%s];' % ', '.join('"%s"' % c for c in CATS), '',
       '    /// <summary>Start code point of each run of equal general category (sorted).</summary>',
       arr('CatStart', 'int', [r[0] for r in runs]), '',
       '    /// <summary>Category code of each run.</summary>', arr('CatCode', 'byte', [r[1] for r in runs], 24), '',
       '    /// <summary>Code points with a simple case folding (sorted) and their folded values.</summary>',
       arr('FoldFrom', 'int', fk), '', arr('FoldTo', 'int', [fold[c] for c in fk]), '',
       '    /// <summary>Letters that are a Latin base plus removable marks: code point, base, number of marks.</summary>',
       arr('DiaFrom', 'int', [d[0] for d in dia]), '', arr('DiaBase', 'int', [d[1] for d in dia]), '',
       arr('DiaMarks', 'byte', [d[2] for d in dia], 24), '}', '']
out = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'OneLite', 'Internal', 'Text', 'UnicodeTables.g.cs')
open(out, 'w', encoding='utf8', newline='\n').write('\n'.join(src))
print(len(runs), 'category runs,', len(fk), 'folds,', len(dia), 'diacritic letters')
